// Builds src/data/leaders.mjs (every Leader card: id, name, colors, set) from
// OPTCG Sim's own card database, so new sets (OP18, EB05, …) arrive with the game:
//   npm run ingest-leaders                      newest ~/<version>_Windows install
//   npm run ingest-leaders -- "D:\Games\1.31a_Windows"
//
// Cards live in Builds_Windows/OPTCGSim_Data/resources.assets as Unity-serialized
// records (str = i32 byteLength + utf8 bytes, padded to 4):
//   str id, str id, i32 ?, i32 cardType (0 = Leader), str name, i32 attribute,
//   i32 life, i32 power, i32 ?, i32 nTypes, i32 types[n], i32 ?, i32 nColors, i32 colors[n]
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
export const COLORS = ['Red', 'Green', 'Blue', 'Purple', 'Black', 'Yellow']
export const ASSETS = path.join('Builds_Windows', 'OPTCGSim_Data', 'resources.assets')

export function findInstall(arg) {
  if (arg) return path.resolve(arg)
  const dirs = [os.homedir(), path.join(os.homedir(), 'Downloads'), path.join(os.homedir(), 'Desktop')]
  const found = dirs
    .flatMap((d) => (fs.existsSync(d) ? fs.readdirSync(d).map((n) => path.join(d, n)) : []))
    .filter((p) => /^\d+\.\d+\w*_Windows$/i.test(path.basename(p)) && fs.existsSync(path.join(p, ASSETS)))
    .sort((a, b) => fs.statSync(b).mtimeMs - fs.statSync(a).mtimeMs)
  if (!found.length) throw new Error('No OPTCG Sim install found; pass its folder as an argument.')
  return found[0]
}

/** All Leader records in a resources.assets buffer. */
export function parseLeaders(buf) {
  const text = buf.toString('latin1') // one char per byte, so match offsets are byte offsets
  const re = /\x08\x00\x00\x00([A-Z]+\d*-\d{3})\x08\x00\x00\x00\1/g
  const leaders = new Map()
  let m
  while ((m = re.exec(text))) {
    const id = m[1]
    let j = m.index + m[0].length
    const i32 = () => {
      const v = buf.readInt32LE(j)
      j += 4
      return v
    }
    try {
      i32()
      if (i32() !== 0) continue // not a Leader
      const n = i32()
      if (n <= 0 || n > 80) continue
      const name = buf.toString('utf8', j, j + n).replace(/\s+/g, ' ').trim()
      j += n + ((4 - (n % 4)) % 4)
      i32(), i32() // attribute, life
      const power = i32()
      i32()
      const nTypes = i32()
      if (power < 0 || power > 20000 || nTypes < 0 || nTypes > 8) continue
      j += nTypes * 4
      i32()
      const nColors = i32()
      if (nColors < 1 || nColors > 3) continue
      const colors = Array.from({ length: nColors }, i32).map((c) => COLORS[c])
      if (!name || colors.some((c) => !c) || leaders.has(id)) continue
      leaders.set(id, { id, name, colors, set: id.split('-')[0] })
    } catch {
      // record ran past the end of the buffer
    }
  }
  return [...leaders.values()].sort((a, b) => a.id.localeCompare(b.id, 'en', { numeric: true }))
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const install = findInstall(process.argv[2])
  const list = parseLeaders(fs.readFileSync(path.join(install, ASSETS)))
  const out = path.join(root, 'src', 'data', 'leaders.mjs')
  // Keep previously known leaders the sim's records don't expose (e.g. PRB reprints).
  const have = new Set(list.map((l) => l.id))
  const prev = fs.existsSync(out) ? (await import(`${pathToFileURL(out).href}?${Date.now()}`)).LEADERS : []
  for (const l of prev) if (!have.has(l.id)) list.push(l)
  list.sort((a, b) => a.id.localeCompare(b.id, 'en', { numeric: true }))
  const body = list.map((l) => `  ${JSON.stringify(l)},`).join('\n')
  fs.writeFileSync(out, `// Generated by scripts/ingest-leaders.mjs from OPTCG Sim's card data. Do not edit by hand.\nexport const LEADERS = [\n${body}\n]\n`)
  const sets = [...new Set(list.map((l) => l.set))]
  console.log(`${list.length} leaders from ${sets.length} sets → ${path.relative(root, out)}`)
}
